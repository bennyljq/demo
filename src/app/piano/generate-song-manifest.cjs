const fs = require('node:fs');
const path = require('node:path');
const configured = require('./song-library.config.cjs');

const root = path.resolve(__dirname, '../../assets/piano/tracks');
const destination = path.join(__dirname, 'song-manifest.generated.ts');
if (configured.length !== 4 || new Set(configured.map(song => song.id)).size !== configured.length)
  throw new Error('The curated song library must contain four unique IDs.');
for (const song of configured) {
  if (!/\.(mxl|musicxml)$/i.test(song.file) || !fs.existsSync(path.join(root, song.file)))
    throw new Error(`Missing configured MusicXML score: ${song.file}`);
}
const output = `// Generated by generate-song-manifest.cjs from song-library.config.cjs. Do not edit.\n` +
  `export interface SongEntry { readonly id: string; readonly title: string; readonly file: string; ` +
  `readonly composer: string; readonly credit?: string; readonly difficulty: string; readonly playerPerformedMelody?: boolean }\n` +
  `export const SONGS: readonly SongEntry[] = ${JSON.stringify(configured, null, 2)};\n`;
if (!fs.existsSync(destination) || fs.readFileSync(destination, 'utf8') !== output) fs.writeFileSync(destination, output);
console.log(`Generated ${configured.length} curated MusicXML songs.`);
