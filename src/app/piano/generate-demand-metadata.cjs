const { spawnSync } = require('node:child_process');
const { writeFileSync } = require('node:fs');
const { join } = require('node:path');

// Karma runs the same importer and chart builders as the game; this script only captures their report.
const args = ['test', '--', '--watch=false', '--browsers=ChromeHeadless',
  '--ts-config=src/app/piano/tsconfig.spec.json',
  '--include=src/app/piano/charts/piano-demand.report.spec.ts'];
const run = spawnSync('npm', args, { cwd: join(__dirname, '..', '..', '..'),
  encoding: 'utf8', shell: process.platform === 'win32' });
const output = `${run.stdout ?? ''}\n${run.stderr ?? ''}`;
if (run.status !== 0) { process.stderr.write(output); process.exit(run.status ?? 1); }
const encoded = /PIANO_DEMAND_BASE64=([A-Za-z0-9+/=]+)/.exec(output)?.[1];
if (!encoded) throw new Error('Demand test did not emit its report.');
const report = JSON.parse(Buffer.from(encoded, 'base64').toString('utf8'));
writeFileSync(join(__dirname, 'song-demand.generated.ts'),
  `// Generated by node src/app/piano/generate-demand-metadata.cjs. Do not edit.\n` +
  `import type { DemandMetrics } from './gameplay/piano-wpm';\n` +
  `import type { PianoMode } from './gameplay/piano-mode';\n\n` +
  `export const SONG_DEMAND: Readonly<Record<string, Readonly<Record<PianoMode, DemandMetrics>>>> = ${JSON.stringify(report, null, 2)};\n`);
process.stdout.write('Generated song-demand.generated.ts from imported scores.\n');
